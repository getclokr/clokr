/**
 * Issue #1069 (D-06, D-07, D-11, D-19, D-20) - the control codes, German texts and audit markers of
 * the Betriebsurlaub booking. Pure: a type-only import and no runtime import except the one date
 * formatter, so the cycle gate sees a leaf next to its siblings.
 *
 * A code is the control value of a refusal or an audit marker, the German text is display only
 * (CLAUDE.md "Never use a new display string as a control value").
 *
 * Deliberately NOT re-exported from `contexts/absence/index.ts` (import-cycle cap 22); importers:
 * `company-shutdown/booking.ts` and `api/company-shutdowns.ts`.
 */
import { formatDateDe } from "../leave-decision";

/** Value of `newValue.trigger` on the CREATE audit of a request generated by a Betriebsurlaub. */
export const COMPANY_SHUTDOWN_TRIGGER = "COMPANY_SHUTDOWN";

/** Audit action of the one summary row a booking run writes on the CompanyShutdown (ids and counts only). */
export const COMPANY_SHUTDOWN_BOOKED = "COMPANY_SHUTDOWN_BOOKED";

/** Two active Betriebsurlaube of one tenant may not overlap (409). */
export const COMPANY_SHUTDOWN_OVERLAP = "COMPANY_SHUTDOWN_OVERLAP";

/** Another booking run of the same Betriebsurlaub holds the lock (409). */
export const COMPANY_SHUTDOWN_BOOKING_RUNNING = "COMPANY_SHUTDOWN_BOOKING_RUNNING";

/** German texts of the refusal codes above - display only. */
export const COMPANY_SHUTDOWN_MESSAGES: Readonly<Record<string, string>> = {
  [COMPANY_SHUTDOWN_OVERLAP]: "Der Zeitraum überschneidet sich mit einem anderen Betriebsurlaub.",
  [COMPANY_SHUTDOWN_BOOKING_RUNNING]:
    "Für diesen Betriebsurlaub läuft gerade eine Buchung. Bitte versuche es gleich noch einmal.",
};

/** Name of the transaction-scoped advisory lock of one Betriebsurlaub (one booking run at a time). */
export function companyShutdownLockName(shutdownId: string): string {
  return `company-shutdown-booking:${shutdownId}`;
}

/**
 * The system reason of the leave-limit exception an approval passes (D-07): a staffing limit cannot
 * apply while the business is closed. At least 10 characters by construction (the #836 rule).
 */
export function limitExceptionReasonFor(shutdown: {
  name: string;
  startDate: Date;
  endDate: Date;
}): string {
  return `Betriebsurlaub „${shutdown.name}“ vom ${formatDateDe(shutdown.startDate)} bis ${formatDateDe(shutdown.endDate)}`;
}
