/** Name of the transaction-scoped advisory lock of one Betriebsurlaub (one booking run at a time). */
export function companyShutdownLockName(shutdownId: string): string {
  return `company-shutdown-booking:${shutdownId}`;
}

/**
 * The system reason of the leave-limit exception an approval passes (D-07): a staffing limit cannot
 * apply while the business is closed. At least 10 characters by construction (the #836 rule).
 */
export function limitExceptionReasonFor(shutdown: {
  name: string;
  startDate: Date;
  endDate: Date;
}): string {
  return `Betriebsurlaub „${shutdown.name}“ vom ${formatDateDe(shutdown.startDate)} bis ${formatDateDe(shutdown.endDate)}`;
}
